#!/usr/bin/env python3
"""Keep each built-in source type's docs page in step with the code.

`okg deployment source-types` prints what each built-in type reads, its
settings, its access, and how updates and removals work. Each type has a page
at docs/use/sources/<type>.md; the part between the `source-type` markers is
rendered here from the same catalog, so the page cannot drift from the
command. The rest of the page (adding it, checking it, failures) is written
by hand.

    python scripts/render_source_type_pages.py          # report drift, exit 1
    python scripts/render_source_type_pages.py --write  # rewrite the blocks
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "docs" / "use" / "sources"
START = "<!-- source-type:start (generated by scripts/render_source_type_pages.py) -->"
END = "<!-- source-type:end -->"
#: Headings every source-type page carries, generated or hand-written.
TEMPLATE_HEADINGS = (
    "## What it reads",
    "## Settings",
    "## Access",
    "## Updates and removals",
    "## Add it",
    "## Check it",
    "## When it fails",
)


def source_types() -> list[dict[str, Any]]:
    from okg.substrate.sources.guided_catalog import SUPPORTED_SOURCE_TYPES

    return [t.describe() for t in SUPPORTED_SOURCE_TYPES.values()]


def _default(value: Any) -> str:
    if value is None:
        return ""
    return f"`{json.dumps(value)}`"


def render_block(item: dict[str, Any]) -> str:
    records = ", ".join(f"`{name}`" for name in item["records"])
    rows = [
        "| Setting | Required | Default | Meaning |",
        "| --- | --- | --- | --- |",
    ]
    for setting in item["settings"]:
        description = setting["description"].replace("|", "\\|")
        rows.append(
            f"| `{setting['name']}` | {'yes' if setting['required'] else 'no'} "
            f"| {_default(setting['default'])} | {description} |"
        )
    lines = [
        START,
        "## What it reads",
        "",
        item["summary"],
        "",
        f"Record types it adds: {records}.",
        "",
        "## Settings",
        "",
        *rows,
        "",
        "## Access",
        "",
        item["access"],
        "",
        "## Updates and removals",
        "",
        item["update_behaviour"],
        item["removal_behaviour"],
        item["refresh"],
        END,
    ]
    return "\n".join(lines)


def page_path(type_id: str) -> Path:
    return PAGES / f"{type_id}.md"


def replace_block(text: str, block: str) -> str:
    head, sep, rest = text.partition(START)
    if not sep:
        raise ValueError("missing the source-type start marker")
    _old, sep, tail = rest.partition(END)
    if not sep:
        raise ValueError("missing the source-type end marker")
    return head + block + tail


def problems() -> list[str]:
    found: list[str] = []
    for item in source_types():
        path = page_path(item["type"])
        if not path.exists():
            found.append(f"{path.relative_to(ROOT)}: no page for source type {item['type']!r}")
            continue
        text = path.read_text(encoding="utf-8")
        try:
            expected = replace_block(text, render_block(item))
        except ValueError as exc:
            found.append(f"{path.relative_to(ROOT)}: {exc}")
            continue
        if expected != text:
            found.append(
                f"{path.relative_to(ROOT)}: generated block is out of date; "
                "run python scripts/render_source_type_pages.py --write"
            )
        missing = [h for h in TEMPLATE_HEADINGS if f"\n{h}\n" not in expected]
        if missing:
            found.append(f"{path.relative_to(ROOT)}: missing headings {missing}")
    return found


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite the generated blocks")
    args = parser.parse_args(argv)
    if args.write:
        for item in source_types():
            path = page_path(item["type"])
            if not path.exists():
                continue  # reported below; write the page by hand first
            path.write_text(
                replace_block(path.read_text(encoding="utf-8"), render_block(item)),
                encoding="utf-8",
            )
    found = problems()
    for line in found:
        print(line, file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    raise SystemExit(main())
