def _result(answer: str) -> TaskResult:
    return TaskResult(
        instance_id="stark-prime/test/4",
        arm="echo",
        status="completed",
        answer=answer,
        metrics=TaskMetrics(0, 0, 0, 0, 0, 0.0),
    )


def _instance(qa_root: Path):
    instances = StarkPrimeAdapter().load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    return instances[0]        # row 4, gold [11]


def test_score_task_reports_every_metric_and_the_protocol_state(
    qa_root: Path,
) -> None:
    adapter = StarkPrimeAdapter()
    instance = _instance(qa_root)
    ids = [99, 11] + list(range(200, 218))
    score = adapter.score_task(
        run_dir=Path("/nonexistent"), data_root=Path("/nonexistent"),
        instance=instance,
        result=_result("RANKED_ENTITY_IDS: " + ", ".join(map(str, ids))),
    )
    assert isinstance(score, Score)
    assert score.kind == "ranked_retrieval"
    assert score.value == pytest.approx(0.5)
    assert score.detail["mrr"] == pytest.approx(0.5)
    assert score.detail["hit@1"] == 0.0
    assert score.detail["hit@3"] == 1.0
    assert score.detail["recall@20"] == 1.0
    assert score.detail["emitted"] == TOP_K
    assert score.detail["protocol_complete"] is True
    assert score.detail["protocol"] == "STARK-RANK-1"


def test_a_short_emission_is_scored_and_flagged(qa_root: Path) -> None:
    """P3 is violated below `TOP_K`, and the score says so rather than the
    run silently mixing two scoring regimes."""
    adapter = StarkPrimeAdapter()
    score = adapter.score_task(
        run_dir=Path("/nonexistent"), data_root=Path("/nonexistent"),
        instance=_instance(qa_root),
        result=_result("RANKED_ENTITY_IDS: 11, 12"),
    )
    assert score.value == 1.0
    assert score.detail["emitted"] == 2
    assert score.detail["protocol_complete"] is False


def test_an_empty_emission_is_a_defined_miss_not_a_skip(
    qa_root: Path,
) -> None:
    """The reference evaluator cannot score an empty prediction at all —
    `min(pred)` of an empty tensor raises. The protocol defines it as a
    miss on every metric, recorded with the reason; it is never an
    unscored task and never a crash."""
    adapter = StarkPrimeAdapter()
    score = adapter.score_task(
        run_dir=Path("/nonexistent"), data_root=Path("/nonexistent"),
        instance=_instance(qa_root),
        result=_result("I do not know."),
    )
    assert score.value == 0.0
    assert score.unscored_reason is None
    assert score.detail["emitted"] == 0
    assert all(score.detail[m] == 0.0 for m in METRICS)
    assert "empty emission" in score.detail["reason"]


def test_recall_denominator_is_the_full_gold_set(qa_root: Path) -> None:
    """Row 2's gold is a single id; row 3's is three. Recall@20 divides by
    the gold size, matching the reference's `relevant / target.sum()`."""
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    row3 = next(i for i in instances if i.extra["row_id"] == 2)
    assert row3.gold["answer_ids"] == [100]
    assert _score_ranked([100, 1, 2], [3, 4, 5]) == {
        "mrr": 0.0, "hit@1": 0.0, "hit@3": 0.0, "hit@5": 0.0,
        "recall@20": 0.0,
    }
    assert _score_ranked([3, 1, 2], [3, 4, 5])["recall@20"] == pytest.approx(
        1 / 3)


def test_pilot_subset_is_deterministic(qa_root: Path) -> None:
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    assert adapter.pilot_subset(instances) == adapter.pilot_subset(instances)
    assert adapter.pilot_subset(instances) == instances[: adapter.pilot_size]


