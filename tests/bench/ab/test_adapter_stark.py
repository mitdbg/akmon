def test_gold_is_sealed_out_of_the_prompt(qa_root: Path) -> None:
    """The prompt is a pure function of (preamble, question, instructions).

    Asserted as an equality rather than as "the gold digits do not appear":
    the preamble states the corpus size, `8,100,498` contains `100`, and a
    substring test would have to be weakened until it caught nothing."""
    from okg.bench.ab.adapters.stark import (
        INSTRUCTIONS,
        OPEN_BOOK_PREAMBLE,
    )

    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    by_row = {i: q for i, q, _ in QA_ROWS}
    for inst in instances:
        assert inst.gold["answer_ids"]
        assert "gold" not in inst.public_dict()
        assert inst.prompt == (
            f"{OPEN_BOOK_PREAMBLE}Question: "
            f"{by_row[inst.extra['row_id']]}{INSTRUCTIONS}"
        )


def test_a_snapshot_holding_the_qa_table_is_refused(
    qa_root: Path, tmp_path: Path
) -> None:
    """`stark_qa.csv` carries `answer_ids` for EVERY row including test, and
    there is no answer-free copy in the release, so a snapshot holding it is
    a gold-bearing snapshot mounted read-only into every arm."""
    snapshot = tmp_path / "snapshot"
    (snapshot / "skb" / "prime").mkdir(parents=True)
    (snapshot / "stark_qa.csv").write_text("id,query,answer_ids\n")
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    with pytest.raises(DatasetError, match="gold-bearing files"):
        adapter.bind_corpus(instances, {"snapshot_dir": str(snapshot)})


@pytest.mark.parametrize("name", FORBIDDEN_SNAPSHOT_NAMES)
def test_every_forbidden_name_is_refused(
    qa_root: Path, tmp_path: Path, name: str
) -> None:
    snapshot = tmp_path / "snapshot"
    (snapshot / "nested" / "deep").mkdir(parents=True)
    (snapshot / "nested" / "deep" / name).write_text("x")
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    with pytest.raises(DatasetError, match="gold-bearing files"):
        adapter.bind_corpus(instances, {"snapshot_dir": str(snapshot)})


def test_a_clean_snapshot_binds(qa_root: Path, tmp_path: Path) -> None:
    """The COMPLEMENT of the refusal. Without it every test above would
    still pass on an adapter that refused unconditionally."""
    snapshot = tmp_path / "snapshot"
    (snapshot / "skb" / "prime" / "processed").mkdir(parents=True)
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    bound = adapter.bind_corpus(instances, {"snapshot_dir": str(snapshot)})
    assert all(str(snapshot) in i.prompt for i in bound)
    assert all(i.extra["add_dirs"] == [str(snapshot)] for i in bound)
    assert all("{SNAPSHOT_DIR}" not in i.prompt for i in bound)


