def test_parse_takes_the_last_answer_line() -> None:
    ranked, detail = parse_ranked_ids(
        "thinking...\nRANKED_ENTITY_IDS: 1, 2\nno wait\n"
        "RANKED_ENTITY_IDS: 5, 6, 7\n"
    )
    assert ranked == [5, 6, 7]
    assert detail["answer_line_found"] is True


def test_parse_counts_everything_it_drops() -> None:
    """Nothing is silently coerced, padded or reordered — every dropped
    token is named in the score detail."""
    ranked, detail = parse_ranked_ids(
        "RANKED_ENTITY_IDS: 5, five, 5, 999999999, -3, 6\n"
    )
    assert ranked == [5, 6]
    assert detail["unparsed_tokens"] == ["five"]
    assert detail["duplicate_ids"] == [5]
    assert sorted(detail["out_of_range_ids"]) == [-3, 999999999]


def test_parse_truncates_beyond_top_k() -> None:
    ranked, detail = parse_ranked_ids(
        "RANKED_ENTITY_IDS: " + ", ".join(str(i) for i in range(30))
    )
    assert ranked == list(range(TOP_K))
    assert detail["truncated_beyond_top_k"] == 10


def test_parse_reports_a_missing_answer_line() -> None:
    ranked, detail = parse_ranked_ids("I could not find anything.")
    assert ranked == []
    assert detail == {"answer_line_found": False}


