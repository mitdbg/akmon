def test_splits_come_from_index_files(qa_root: Path) -> None:
    """req.stark.adapter: the QA table is one flat table in no split order,
    and `split/*.index` is the ONLY statement of which question is in which
    split. A positional slice would score a different set entirely."""
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)

    assert [i.extra["row_id"] for i in instances] == SPLIT_ROWS["test"]
    assert [i.prompt.count("which anatomy expresses GPANK1?") for i in
            instances] == [1, 0]
    # ...and NOT the last-N slice a naive implementation would take.
    assert [i.extra["row_id"] for i in instances] != [6, 7]
    assert {i.extra["split"] for i in instances} == {DEFAULT_SPLIT}

    for split, ids in SPLIT_ROWS.items():
        assert read_split_ids(qa_root, split) == ids


def test_split_index_order_is_preserved(qa_root: Path) -> None:
    """The index files are shuffles, and the file's own line order is the
    run order. Sorting them would be a different, undeclared ordering."""
    assert read_split_ids(qa_root, "test") == [4, 2]
    assert read_split_ids(qa_root, "test") != sorted([4, 2])


def test_test_0_1_is_filtered_on_the_release_s_own_stamp(
    qa_root: Path,
) -> None:
    adapter = StarkPrimeAdapter()
    instances = adapter.load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    small = adapter.subset(instances, "test-0.1")
    assert [i.extra["row_id"] for i in small] == SPLIT_ROWS["test-0.1"]
    assert all(i.extra["in_test_0_1"] for i in small)
    assert adapter.subset(instances, "test") == instances


