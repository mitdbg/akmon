"""STaRK-Prime adapter: splits come from the index files, and the emission
protocol reproduces the reference evaluator.

PACT okg-bench-graph-benchmarks / req.stark.adapter, task.stark.adapter.

`fixtures/stark_prime_reference_metrics.json` holds 136 cases scored by the
VERBATIM `stark_qa/evaluator.py` `Evaluator.evaluate` under torch 2.9 /
torchmetrics 1.9.0 (generated by `.scratch/make_oracle_fixture.py`). The
oracle needs torch; CI does not have it and must not, so its answers are
pinned and `_score_ranked` is checked against them. Regenerate the fixture
if the protocol or the metric list changes — never edit it to match.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from okg.bench.ab.adapters.stark import (
    DEFAULT_SPLIT,
    FORBIDDEN_SNAPSHOT_NAMES,
    METRICS,
    SPLIT_FILES,
    TOP_K,
    StarkPrimeAdapter,
    _score_ranked,
    parse_ranked_ids,
    protocol_scores,
    read_split_ids,
)
from okg.bench.ab.errors import DatasetError
from okg.bench.ab.model import Score, TaskMetrics, TaskResult

FIXTURE_DIR = Path(__file__).parent / "fixtures"
ORACLE = json.loads(
    (FIXTURE_DIR / "stark_prime_reference_metrics.json").read_text()
)

#: A miniature QA release: 8 questions, a 4/2/2 split, and a `test-0.1`
#: that is a subset of test. Row ORDER is deliberately not split order, so
#: a `df[-2:]` implementation scores different questions than the index
#: files name.
QA_ROWS = [
    (0, "which drug treats migraine?", "[42]"),
    (1, "which gene interacts with PAK1?", "[7, 9]"),
    (2, "what causes fever?", "[100]"),
    (3, "which pathway involves NCK2?", "[3, 4, 5]"),
    (4, "which anatomy expresses GPANK1?", "[11]"),
    (5, "what is contraindicated with aspirin?", "[64]"),
    (6, "which phenotype accompanies X?", "[8]"),
    (7, "which exposure links to asthma?", "[12, 13]"),
]
SPLIT_ROWS = {
    "train": [5, 0, 3, 6],
    "val": [1, 7],
    "test": [4, 2],
    "test-0.1": [2],
}


@pytest.fixture()
def qa_root(tmp_path: Path) -> Path:
    root = tmp_path / "cache"
    root.mkdir()
    lines = ["id,query,answer_ids"]
    lines += [f'{i},"{q}","{a}"' for i, q, a in QA_ROWS]
    (root / "stark_qa.csv").write_text("\n".join(lines) + "\n")
    for split, ids in SPLIT_ROWS.items():
        (root / f"{split}.index").write_text(
            "\n".join(str(i) for i in ids) + "\n")
    return root


