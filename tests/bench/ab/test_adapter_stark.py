def test_scoring_reproduces_the_reference_evaluator() -> None:
    """req.stark.adapter: `_score_ranked` IS `stark_qa/evaluator.py`'s
    semantics for a STARK-RANK-1 emission.

    136 pinned cases — hits at every rank, multi-gold, complete misses,
    short lists, single-id lists, and three candidate-space sizes — each
    scored by the real `Evaluator` under torch. float32 tolerance because
    the reference builds float tensors."""
    assert ORACLE["metrics"] == list(METRICS)
    assert ORACLE["top_k"] == TOP_K
    assert len(ORACLE["cases"]) >= 100
    for case in ORACLE["cases"]:
        got = _score_ranked(case["ranked"], case["gold"])
        for metric in METRICS:
            assert abs(got[metric] - case["reference"][metric]) < 1e-6, (
                f"{case['label']}: {metric} {got[metric]} != "
                f"{case['reference'][metric]}"
            )


def test_the_reference_fixture_is_not_all_zeros() -> None:
    """A fixture of zeros would make the test above vacuous: an adapter
    returning 0.0 for everything would reproduce it exactly."""
    values = [c["reference"] for c in ORACLE["cases"]]
    for metric in METRICS:
        distinct = {round(v[metric], 6) for v in values}
        # hit@k is binary by definition, so it can only ever take two
        # values; both must occur or the cases are all hits or all misses.
        expected = 2 if metric.startswith("hit") else 3
        assert len(distinct) >= expected, f"{metric} takes only {distinct}"
        assert {0.0, 1.0} <= distinct or not metric.startswith("hit")
    assert any(v["mrr"] == 1.0 for v in values)
    assert any(v["mrr"] == 0.0 for v in values)
    assert len({round(v["mrr"], 6) for v in values}) > 5
    assert any(0.0 < v["recall@20"] < 1.0 for v in values)


def test_scoring_is_candidate_set_independent() -> None:
    """The protocol's point: with every emitted score in (0, 1] and the
    list at full length, the reference's ~129,000-element floor tie block
    cannot reach any metric, so the same emission scores the same in a
    500-entity space and a 129,375-entity one. That is what lets this
    module score without torch or the SKB."""
    spaces = [
        c for c in ORACLE["cases"]
        if c["label"].startswith("gold at rank 2 of 20, candidate space")
    ]
    assert len(spaces) == 3
    first = spaces[0]["reference"]
    for case in spaces[1:]:
        assert case["reference"] == first
        assert case["n_candidates"] != spaces[0]["n_candidates"]


def test_protocol_scores_satisfy_both_evaluator_conditions() -> None:
    """P1: every emitted score > 0, or a gold the arm DID rank is masked
    out of MRR and recall while still counting for hit@k.
    P2: the smallest score <= 1, so the evaluator's `min(pred) - 1` floor
    is <= 0 and every unnamed candidate is masked out of MRR and recall."""
    for n in (1, 2, 5, 19, TOP_K):
        scores = protocol_scores(list(range(n)))
        values = list(scores.values())
        assert len(scores) == n
        assert all(v > 0.0 for v in values), "P1"
        assert min(values) <= 1.0, "P2"
        assert max(values) <= 1.0
        assert values == sorted(values, reverse=True)
        assert len(set(values)) == n, "no internal ties"
    assert protocol_scores([]) == {}


def test_the_arm_never_supplies_a_score(qa_root: Path) -> None:
    """The prompt asks for an ORDER, not for numbers: an arm-side score
    scale is exactly what P1/P2 make load-bearing, so the adapter owns
    it."""
    instances = StarkPrimeAdapter().load_instances(
        data_root=Path("/nonexistent"), offline_fixture=qa_root)
    prompt = instances[0].prompt
    assert "Do not emit scores" in prompt
    assert f"{TOP_K} ids" in prompt


