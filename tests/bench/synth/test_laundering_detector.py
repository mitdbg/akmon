"""PACT ``concord-measurement-integrity`` — req.mi.reading-loss-visible.

Can a reader's silent loss be detected WITHOUT gold? For the loss that actually
occurs, no — and these witnesses pin why, so the negative result cannot be
mistaken later for an untried idea.

The extractor already carries a gold-free instrument: it refuses a fact whose
quote is not a verbatim substring of the document ("the value was invented or
altered"). It catches INVENTION. The laundering measured on the prose run is
OMISSION — the model never returned the fact — and no instrument that inspects
the extractor's OUTPUT can see something missing from that output.
"""
from __future__ import annotations

import json
import pathlib
import re


#: The laundered slice of the prose reading run, committed so these witnesses
#: actually RUN. The full run is ~2MB of corpus regenerated by a paid model
#: call; committing it would put megabytes of generated data into review, and
#: pointing at the scratch directory where it happened to live made both
#: witnesses SKIP everywhere but the author's machine — a test that runs
#: nowhere asserts nothing, and CI's result gate refuses a classified test that
#: never produced a passing result.
#:
#: The subset is the 8 documents whose facts the reader lost, plus their 104
#: claims and 25 gold sites. It is faithful, not merely smaller: both verdicts
#: are computed from `flagged & gold` and from the sites that failed to carry,
#: so documents outside the laundered set cannot change either one. Verified
#: against the full run on 2026-08-30 — gold=8, caught=[] and
#: classes={dangling_entity, entity_swap} on both.
_RUN = pathlib.Path(__file__).resolve().parent / "fixtures/prose_laundering"


def _nums(text) -> list[str]:
    return re.findall(r"-?\d+(?:\.\d+)?", str(text))


# --------------------------------------------------------------------------- #
# The instrument that exists, and what it is blind to.                        #
# --------------------------------------------------------------------------- #
def test_the_extractor_refuses_a_quote_it_cannot_find(tmp_path) -> None:
    """The gold-free instrument, exercised directly: a value the model did not
    read from the document is refused, and the refusal names the cause."""
    from okg.bench.synth.llm_extract import _quote_offsets

    document = "## Measurements\n\nHer A1c was 6.0 %.\nWeight was 79.1 kg.\n"
    assert _quote_offsets(document, "Her A1c was 6.0 %."), (
        "a verbatim quote must be locatable"
    )
    assert _quote_offsets(document, "Her A1c was 9.9 %.") == [], (
        "an INVENTED value must not be locatable — this is the whole signal"
    )


def test_an_omitted_fact_leaves_nothing_for_any_output_instrument_to_check() -> None:
    """THE structural point. Every gold-free instrument inspects the extractor's
    OUTPUT. An omission is absent from that output, so there is no value to
    contain-check and no quote to verify."""
    document = "## Medications\n\nZenvorix 64fb 25 MG Oral Tablet.\n"
    returned: list[dict] = []          # the model silently returned nothing
    # a containment instrument has no claim to examine
    assert [c for c in returned if str(c.get("value")) not in document] == []
    # and a quote instrument has no quote to examine
    assert [c for c in returned if c.get("quote")] == []
    # yet the document plainly carries a fact
    assert "Zenvorix" in document


# --------------------------------------------------------------------------- #
# Graded on the sealed run.                                                    #
# --------------------------------------------------------------------------- #
def test_no_gold_free_instrument_catches_the_measured_laundering() -> None:
    """ACCEPTANCE. Graded against gold — gold is the GRADER, never an input."""
    manifest = json.loads((_RUN / "benchmark-manifest.json").read_text())
    claims = json.loads((_RUN / "extracted-claims-corrupted.json").read_text())
    docs = {
        f.name: f.read_text(encoding="utf-8")
        for f in (_RUN / "corpus_corrupted").glob("*.md")
    }
    assert docs and not all(len(v) == 64 for v in docs.values()), (
        "corrupted_corpus maps doc->DIGEST; the BYTES are on disk, and reading "
        "the digests instead silently flags everything"
    )

    gold: set[str] = set()
    for site in manifest["gold"]["corruptions"]:
        post = _nums(site["post_text"])
        same = [c for c in claims if c["source_id"] == site["doc"]]
        carried = (
            any(_nums(c["value"]) == post for c in same) if post
            else any(str(site["post_text"]).lower() in str(c["value"]).lower()
                     for c in same)
        )
        if not carried:
            gold.add(site["doc"])
    assert gold, "no laundering in the sealed run — nothing to grade against"

    def flagged_by_containment() -> set[str]:
        out = set()
        for claim in claims:
            text = docs.get(claim["source_id"], "")
            want = _nums(claim["value"])
            ok = (all(n in set(_nums(text)) for n in want) if want
                  else str(claim["value"]).lower() in text.lower())
            if not ok:
                out.add(claim["source_id"])
        return out

    caught = flagged_by_containment() & gold
    assert caught == set(), (
        "a containment instrument caught laundering — the structural claim in "
        f"this module is stale and must be revised: {sorted(caught)}"
    )


def test_the_measured_laundering_is_identity_corruption_not_value_corruption() -> None:
    """WHY no value-based instrument can work here."""
    manifest = json.loads((_RUN / "benchmark-manifest.json").read_text())
    claims = json.loads((_RUN / "extracted-claims-corrupted.json").read_text())
    classes: set[str] = set()
    for site in manifest["gold"]["corruptions"]:
        post = _nums(site["post_text"])
        same = [c for c in claims if c["source_id"] == site["doc"]]
        carried = (
            any(_nums(c["value"]) == post for c in same) if post
            else any(str(site["post_text"]).lower() in str(c["value"]).lower()
                     for c in same)
        )
        if not carried:
            classes.add(site["corruption_class"])
    assert classes <= {"entity_swap", "dangling_entity"}, (
        f"laundering reached a non-identity class: {sorted(classes)} — the "
        "structural explanation in this module no longer covers the data"
    )
