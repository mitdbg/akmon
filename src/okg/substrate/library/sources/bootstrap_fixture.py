"""Bootstrap fixture source adapter.

Reads a local fact-shaped JSON fixture generated by
``okg deployment bootstrap draft``. This adapter exists so the
bootstrap proof slice can run through the normal SourceRunner and
Publisher path without pretending that an arbitrary sample file is a
production connector.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from okg.substrate.library.sources._fixture import FixtureBackedAdapter


@dataclass
class BootstrapFixtureSource(FixtureBackedAdapter):
    name: str = "bootstrap_fixture"
    profile: str = "discovery_crawl"
    fixture_path: Path | str = ""

    # Incremental-source contract (issue #323): a bootstrap fixture is a
    # local fact-shaped JSON file, so the probe is the ContentHashProbe
    # floor inherited from FixtureBackedAdapter (read + hash the fixture;
    # an edit changes the sha, a delete drops the membership entry). This
    # literal is restated here — not just inherited — because the static
    # `deployment_lint` AST reader inspects only the registered class's
    # own body. The runtime `self.change_probe` is built in the base
    # `__post_init__`.
    change_probe_kind = "content_hash"
