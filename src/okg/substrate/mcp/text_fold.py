"""The accent- and case-blind fold behind the `like` condition (issue #3666).

PACT loose-match-3666. `like` keeps a record when a stored string, folded,
contains the folded operand. `like_exact` keeps it when the stored string
contains the operand as written, both put in NFC. Neither rewrites a stored
or served value: the fold is only how two strings are compared.

The fold, in this order:

1. NFKD (compatibility decomposition): an accented letter splits into its
   letter and its marks, and compatibility forms become plain ones (the
   ligature "fi" is f + i, a superscript 2 is 2, a full-width A is A);
2. every nonspacing mark (Unicode category Mn, :data:`MARK_RANGES`) is
   removed;
3. lowercase, by the simple mapping PostgreSQL 17's `pg_c_utf8` collation
   uses;
4. the letters whose lowercase and full case folding disagree are replaced
   by their folded form (:data:`CASEFOLD_REPLACEMENTS`: sharp s is "ss",
   final sigma is sigma, and the old Cyrillic letter variants);
5. a fixed table for letters that do not decompose (:data:`FIXED_TABLE`).

Dotless i stays apart from i, as full case folding keeps them.

The same steps run in Python (:func:`fold`) and in SQL (:func:`fold_sql`),
built only from PostgreSQL built-ins (`normalize`, `regexp_replace`,
`lower ... COLLATE pg_c_utf8`, `replace`), so no migration is needed. The
two generated tables are committed here; :func:`generate_tables` rebuilds
them from Python's Unicode data, and a test asserts the two agree. Another
test runs both folds over every code point on a real database.

`pg_c_utf8` exists from PostgreSQL 17, and `normalize` needs a UTF8
database: :func:`database_problem` names what a database lacks, and the
read is refused by name before any of its statements runs.
"""
